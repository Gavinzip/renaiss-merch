CREATE SCHEMA IF NOT EXISTS field_draw;

CREATE TABLE IF NOT EXISTS field_draw.roster_draw_archives (
    id TEXT PRIMARY KEY, title TEXT NOT NULL, hash TEXT NOT NULL,
    entries_json TEXT NOT NULL, created_at TEXT NOT NULL, operator TEXT NOT NULL,
    cleared_at TEXT NOT NULL, cleared_by TEXT NOT NULL
  );

CREATE TABLE IF NOT EXISTS field_draw.roster_draw_list (
    singleton BIGINT PRIMARY KEY CHECK(singleton=1), id TEXT NOT NULL, title TEXT NOT NULL,
    hash TEXT NOT NULL, entries_json TEXT NOT NULL, created_at TEXT NOT NULL, operator TEXT NOT NULL
  );

CREATE TABLE IF NOT EXISTS field_draw.roster_draw_winners (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, request_id TEXT NOT NULL UNIQUE,
    roster_id TEXT NOT NULL, entry_id TEXT NOT NULL, name TEXT NOT NULL,
    kind TEXT NOT NULL, prize TEXT NOT NULL, drawn_at TEXT NOT NULL, operator TEXT NOT NULL,
    UNIQUE(roster_id,entry_id)
  );

CREATE TABLE IF NOT EXISTS field_draw.draw_room_access_sessions (
    id_hash TEXT PRIMARY KEY, username TEXT NOT NULL, credential_fingerprint TEXT NOT NULL,
    expires_at BIGINT NOT NULL
  );

CREATE TABLE IF NOT EXISTS field_draw.draw_room_login_throttle (
    address_hash TEXT PRIMARY KEY, failures BIGINT NOT NULL, window_start BIGINT NOT NULL,
    locked_until BIGINT NOT NULL
  );
